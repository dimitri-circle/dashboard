#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

function parseArgs(argv) {
  const args = {
    email: "dimitri@circleclick.com",
    out: ".data/auth/circleclick-local-auth.env",
  };

  for (let index = 2; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];

    if (arg === "--email" && next) {
      args.email = next;
      index += 1;
    } else if (arg === "--out" && next) {
      args.out = next;
      index += 1;
    } else if (arg === "--help") {
      args.help = true;
    }
  }

  return args;
}

function printHelp() {
  process.stdout.write(`Create a disposable local auth env file for CircleClick dashboard UI checks.

Usage:
  node .agents/skills/circleclick-authenticated-dashboard/scripts/create-temp-local-auth-env.mjs \\
    --out .data/auth/circleclick-local-auth.env

Options:
  --email  Local login email. Default: dimitri@circleclick.com
  --out    Env file path. Default: .data/auth/circleclick-local-auth.env

The generated file contains temporary secrets and is written under .data/ by default.
Do not print or commit it.
`);
}

function quoteEnv(value) {
  return JSON.stringify(value);
}

function main() {
  const args = parseArgs(process.argv);

  if (args.help) {
    printHelp();
    return;
  }

  const outPath = path.resolve(process.cwd(), args.out);
  const email = args.email.trim().toLowerCase();
  const password = crypto.randomBytes(24).toString("base64url");
  const sessionToken = crypto.randomBytes(32).toString("base64url");

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(
    outPath,
    [
      "# Disposable local dashboard auth for UI verification only.",
      "# Generated by circleclick-authenticated-dashboard skill.",
      "NODE_ENV=development",
      `SEO_APP_EMAIL=${quoteEnv(email)}`,
      `SEO_APP_PASSWORD=${quoteEnv(password)}`,
      `SEO_APP_SESSION_TOKEN=${quoteEnv(sessionToken)}`,
      "",
    ].join("\n"),
    { mode: 0o600 }
  );
  fs.chmodSync(outPath, 0o600);

  process.stdout.write(
    JSON.stringify(
      {
        ok: true,
        out: outPath,
        email,
        variables: ["SEO_APP_EMAIL", "SEO_APP_PASSWORD", "SEO_APP_SESSION_TOKEN"],
      },
      null,
      2
    )
  );
}

try {
  main();
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
}

